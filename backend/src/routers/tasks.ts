import Router from "@koa/router";

import { createTask } from "../controllers/tasks/createTask.js";
import { editTask } from "../controllers/tasks/editTask.js";
import { executeTask } from "../controllers/tasks/executeTask.js";
import { getTask } from "../controllers/tasks/getTask.js";
import { getTaskExecutability } from "../controllers/tasks/getTaskExecutability.js";
import { getTaskPredecessors } from "../controllers/tasks/getTaskPredecessors.js";
import { moveTask } from "../controllers/tasks/moveTask.js";
import { requireAuthentication } from "../middlewares/authRequirer.js";
import { validate } from "../middlewares/zodValidator.js";
import {
  createTaskRequestSchema,
  idRequestSchema,
  moveTaskRequestSchema,
  updateTaskRequestSchema,
} from "../zod/schemas.js";

export const tasksRouter = new Router({ prefix: "/tasks" });

tasksRouter.use(requireAuthentication);

tasksRouter.get("/:id", validate(idRequestSchema), getTask);

// Create a task; task_id is generated by the database
tasksRouter.post("/", validate(createTaskRequestSchema), createTask);
tasksRouter.patch("/:id", validate(updateTaskRequestSchema), editTask);
tasksRouter.patch("/:id/position", validate(moveTaskRequestSchema), moveTask);

tasksRouter.get(
  "/:id/predecessors",
  validate(idRequestSchema),
  getTaskPredecessors,
);
tasksRouter.get(
  "/:id/executable",
  validate(idRequestSchema),
  getTaskExecutability,
);

tasksRouter.post("/:id/execute", validate(idRequestSchema), executeTask);
